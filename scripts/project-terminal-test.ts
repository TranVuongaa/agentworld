import assert from "node:assert/strict";
import { makeCommands } from "../server/commands";
import type { Hub } from "../server/hub";
import type { Sessions } from "../server/sessions";
import type { Planner } from "../server/planner";
import type { Inbox } from "../server/inbox";
import type { Sbx } from "../server/sbx";
import type { SbxMcp } from "../server/sbxMcp";

let hostOpens = 0, workspaceOpens = 0, setupFixes = 0, proxyChanges = 0;
const events: string[] = [];
const agent = { id: "worker", mode: "sandbox", workspacePath: null, cli: "claude", model: "", skills: [] };
const hub = { snap: { config: { project: { githubAuth: "app" }, team: [agent] } }, cfg: (id: string) => id === agent.id ? agent : undefined, configChanged: () => {}, terminal: (_id: string, text: string) => events.push(text), activity: (_type: string, _id: string | null, text: string) => events.push(text) } as unknown as Hub;
const sessions = { openHostShell: () => { hostOpens++; }, openWorkspace: () => { workspaceOpens++; }, runFix: () => { setupFixes++; }, recheckSetup: async () => {} } as unknown as Sessions;
const commands = makeCommands(hub, sessions, {} as Planner, {} as Inbox, { setProxy: async () => { proxyChanges++; } } as unknown as Sbx, {} as SbxMcp);
commands.openHostShell("/", true);
assert.equal(hostOpens, 0, "App project must not open a host shell");
assert(events.some((event) => event.includes("sandbox terminal")));
commands.openWorkspace("worker"); commands.runSetupFix("sbx"); commands.setProxy("http://example.com");
await commands.openEnvFile("worker");
assert.equal(workspaceOpens, 0); assert.equal(setupFixes, 0); assert.equal(proxyChanges, 0);
assert(events.some((event) => event.includes("administrator")));
commands.updateAgent("worker", { mode: "local", workspacePath: "/tmp/other" });
assert.equal(agent.mode, "sandbox"); assert.equal(agent.workspacePath, null);
hub.snap.config.project.githubAuth = "gh";
commands.openHostShell("/", true);
assert.equal(hostOpens, 1, "Local gh development retains its host terminal");
commands.updateAgent("worker", { mode: "local", workspacePath: "/tmp/other" });
assert.equal(agent.mode, "local"); assert.equal(agent.workspacePath, "/tmp/other");
commands.openWorkspace("worker"); commands.runSetupFix("sbx"); await commands.setProxy("http://example.com");
assert.equal(workspaceOpens, 1); assert.equal(setupFixes, 1); assert.equal(proxyChanges, 1);
console.log("App-mode terminal rejects host shells; local gh mode remains available");
